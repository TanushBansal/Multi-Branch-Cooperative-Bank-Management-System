"""Integration tests using a disposable MySQL database, never CooperativeBank.

Run: python -m unittest discover -s tests -p test_transactions.py -v
Requires database-creation permission. Set MYSQL_TEST_CLIENT to the mysql binary
if it is not on PATH. MYSQL_TEST_HOST/PORT/USER default to 127.0.0.1/3306/root;
credentials come from MYSQL_PWD or the client's existing login configuration.
"""

from concurrent.futures import ThreadPoolExecutor
from decimal import Decimal
import os
import sys
from pathlib import Path
import subprocess
import unittest
import uuid


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'demo-app'))
from reports import expand_sql



class TransactionsTest(unittest.TestCase):
    @classmethod
    def run_sql(cls, sql, *, database=True, force=False):
        sql = expand_sql(sql)
        args = [os.environ.get("MYSQL_TEST_CLIENT", "mysql"),
                "--host=" + os.environ.get("MYSQL_TEST_HOST", "127.0.0.1"),
                "--port=" + os.environ.get("MYSQL_TEST_PORT", "3306"),
                "--user=" + os.environ.get("MYSQL_TEST_USER", "root"),
                "--batch", "--skip-column-names", "--raw", "--connect-timeout=5"]
        if database:
            args.append("--database=" + cls.database)
        if force:
            args.append("--force")
        return subprocess.run(args, input=sql, text=True, capture_output=True, timeout=60)

    @classmethod
    def execute(cls, sql, **kwargs):
        result = cls.run_sql(sql, **kwargs)
        if result.returncode or "ERROR " in result.stderr:
            raise AssertionError(result.stderr)
        return result.stdout.strip()

    @classmethod
    def setUpClass(cls):
        cls.database = "cb_transactions_test_" + uuid.uuid4().hex
        cls.execute("CREATE DATABASE " + cls.database, database=False)
        cls.addClassCleanup(cls.drop_database)
        for filename in ("01_schema.sql", "02_constraints_triggers.sql", "04_transactions.sql"):
            sql = (ROOT / "database" / filename).read_text(encoding="utf-8")
            sql = sql.replace("CREATE DATABASE IF NOT EXISTS CooperativeBank;", "")
            sql = sql.replace("USE CooperativeBank;", "USE " + cls.database + ";")
            cls.execute(sql)

    @classmethod
    def drop_database(cls):
        # Only remove the exact disposable database generated by this test run.
        suffix = cls.database.removeprefix("cb_transactions_test_")
        if len(suffix) != 32 or any(c not in "0123456789abcdef" for c in suffix):
            raise AssertionError("Unexpected test database name")
        cls.execute("DROP DATABASE " + cls.database, database=False)

    def setUp(self):
        self.execute("""
            TRUNCATE TABLE TransferDetails;
            DELETE FROM BankTransaction;
            TRUNCATE TABLE SavingsAccount;
            TRUNCATE TABLE CurrentAccount;
            TRUNCATE TABLE FixedDeposit;
            DELETE FROM AccountHolder;
            DELETE FROM Account;
            DELETE FROM Customer;
            DELETE FROM Branch;
            DELETE FROM Bank;
            INSERT INTO Bank VALUES (1, 'Test Bank'), (2, 'Other Bank');
            INSERT INTO Branch VALUES
                (1, 1, 'TEST0000001', 'First', NULL),
                (2, 1, 'TEST0000002', 'Second', NULL),
                (3, 2, 'TEST0000003', 'Other', NULL);
            INSERT INTO Customer (CustomerID, CustomerName, PAN)
                VALUES (1, 'Test Customer', 'ABCDE1234F');
            INSERT INTO Account VALUES
                (1001, 1, 'SAVINGS', 1000, 'ACTIVE', '2026-01-01'),
                (1002, 1, 'CURRENT', 1000, 'ACTIVE', '2026-01-01'),
                (2001, 2, 'CURRENT', 1000, 'ACTIVE', '2026-01-01'),
                (3001, 3, 'CURRENT', 1000, 'ACTIVE', '2026-01-01'),
                (4001, 1, 'FD', 1000, 'ACTIVE', '2026-01-01');
            INSERT INTO AccountHolder VALUES (1,1001),(1,1002),(1,2001),(1,3001),(1,4001);
            INSERT INTO SavingsAccount (AccountNo, InterestRate, MinimumBalance) VALUES (1001, 4, 100);
            INSERT INTO CurrentAccount (AccountNo, MinimumBalance) VALUES (1002, 100), (2001, 100), (3001, 100);
            INSERT INTO FixedDeposit (AccountNo, Principal, InterestRate, StartDate, MaturityDate)
                VALUES (4001,1000,6,'2026-01-01','2027-01-01');
        """)

    def snapshot(self):
        return self.execute("""
            SELECT AccountNo, Balance FROM Account ORDER BY AccountNo;
            SELECT TransactionID, AccountNo, Amount, Status, RequestID
                FROM BankTransaction ORDER BY TransactionID;
            SELECT * FROM TransferDetails ORDER BY TransactionID;
        """)

    def assert_rejected(self, sql, message):
        before = self.snapshot()
        result = self.run_sql(sql)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn(message, result.stderr)
        self.assertEqual(before, self.snapshot())

    def balance(self, account):
        return Decimal(self.execute(f"SELECT Balance FROM Account WHERE AccountNo={account}"))

    def test_subtype_defaults_match_parent(self):
        for table, expected in (("SavingsAccount", "SAVINGS"), ("CurrentAccount", "CURRENT"),
                                ("FixedDeposit", "FD")):
            self.assertEqual(self.execute(f"SELECT DISTINCT AccountType FROM {table}"), expected)

    def test_mismatched_subtype_inserts_are_rejected(self):
        for sql in (
            "INSERT INTO SavingsAccount (AccountNo,InterestRate) VALUES (1002,4)",
            "INSERT INTO CurrentAccount (AccountNo) VALUES (1001)",
            "INSERT INTO FixedDeposit (AccountNo,Principal,InterestRate,StartDate,MaturityDate) "
            "VALUES (1001,1000,6,'2026-01-01','2027-01-01')",
        ):
            with self.subTest(sql=sql):
                self.assert_rejected(sql, "foreign key constraint fails")

    def test_subtype_updates_cannot_bypass_type_checks(self):
        for table, account, wrong_account, wrong_type in (
            ("SavingsAccount", 1001, 1002, "CURRENT"),
            ("CurrentAccount", 1002, 1001, "SAVINGS"),
            ("FixedDeposit", 4001, 1001, "SAVINGS"),
        ):
            before = self.execute(f"SELECT * FROM {table} ORDER BY AccountNo")
            with self.subTest(table=table):
                self.assert_rejected(f"UPDATE {table} SET AccountNo={wrong_account} "
                                     f"WHERE AccountNo={account}", "owner cannot change")
                self.assert_rejected(f"UPDATE {table} SET AccountType='{wrong_type}' "
                                     f"WHERE AccountNo={account}", "Check constraint")
                self.assert_rejected(f"UPDATE {table} SET AccountType=NULL "
                                     f"WHERE AccountNo={account}", "cannot be null")
                self.assertEqual(self.execute(f"SELECT * FROM {table} ORDER BY AccountNo"), before)

    def test_deposit_and_withdrawal(self):
        self.execute("CALL Deposit(1001,500,'BRANCH','d1',@id); SELECT @id;")
        self.execute("CALL Withdraw(1001,200,'ATM','w1',@id);")
        self.assertEqual(self.balance(1001), Decimal("1300"))
        self.assertEqual(self.execute("SELECT GROUP_CONCAT(Status) FROM BankTransaction"),
                         "SUCCESS,SUCCESS")

    def test_intra_and_inter_branch_transfers(self):
        for target in (1002, 2001):
            self.execute(f"CALL Transfer(1001,{target},125,'ONLINE','t{target}',@id);")
            self.assertEqual(self.balance(target), Decimal("1125"))
        self.assertEqual(self.balance(1001), Decimal("750"))
        self.assertEqual(self.execute("SELECT COUNT(*) FROM TransferDetails"), "2")
        self.assertEqual(self.execute("SELECT COUNT(*) FROM BankTransaction "
                                     "WHERE AccountNo IS NULL AND Status='SUCCESS'"), "2")

    def test_invalid_inputs(self):
        for amount in ("NULL", "0", "-1", "1.001", "10000000000000"):
            with self.subTest(amount=amount):
                self.assert_rejected(f"CALL Deposit(1001,{amount},NULL,'bad',@id)", "Amount must")
        for request in ("NULL", "''", "'   '"):
            self.assert_rejected(f"CALL Withdraw(1001,1,NULL,{request},@id)", "RequestID is required")
        self.assert_rejected("CALL Deposit(NULL,1,NULL,'null',@id)", "Account number is required")
        self.assert_rejected("CALL Transfer(1001,1001,1,NULL,'self',@id)", "Two different")
        self.assert_rejected("CALL Transfer(NULL,1001,1,NULL,'null',@id)", "Two different")

    def test_transfer_details_reject_non_transfer_inserts(self):
        self.execute("CALL Deposit(1001,10,NULL,'deposit-details',@id)")
        transaction = self.execute("SELECT TransactionID FROM BankTransaction WHERE RequestID='deposit-details'")
        self.assert_rejected("INSERT INTO TransferDetails (TransactionID,FromAccountNo,ToAccountNo) "
                             f"VALUES ({transaction},1001,2001)", "foreign key constraint fails")

    def test_transfer_details_updates_and_parent_retyping_are_rejected(self):
        self.execute("CALL Transfer(1001,2001,10,NULL,'valid-details',@id)")
        self.execute("CALL Deposit(1001,10,NULL,'other-type',@id)")
        transaction = self.execute("SELECT TransactionID FROM BankTransaction WHERE RequestID='valid-details'")
        deposit = self.execute("SELECT TransactionID FROM BankTransaction WHERE RequestID='other-type'")
        self.assertEqual(self.execute(f"SELECT TransactionType FROM TransferDetails WHERE TransactionID={transaction}"),
                         "TRANSFER")
        self.assert_rejected(f"UPDATE TransferDetails SET TransactionID={deposit} WHERE TransactionID={transaction}",
                             "cannot be reassigned")
        self.assert_rejected(f"UPDATE TransferDetails SET TransactionType='DEPOSIT' WHERE TransactionID={transaction}",
                             "Check constraint")
        self.assert_rejected(f"UPDATE TransferDetails SET TransactionType=NULL WHERE TransactionID={transaction}",
                             "cannot be null")
        # Set AccountNo too, satisfying the parent's existing CHECK so that the
        # composite FK is what blocks the attempt to turn this into a deposit.
        self.assert_rejected("UPDATE BankTransaction SET TransactionType='DEPOSIT',AccountNo=1001 "
                             f"WHERE TransactionID={transaction}", "foreign key constraint fails")

    def test_transfer_details_cannot_be_deleted_or_reassigned(self):
        self.execute("CALL Transfer(1001,2001,10,NULL,'keep-details',@id)")
        transaction = self.execute("SELECT TransactionID FROM BankTransaction WHERE RequestID='keep-details'")
        self.assert_rejected(f"DELETE FROM TransferDetails WHERE TransactionID={transaction}", 'cannot be deleted')
        for changes in ('FromAccountNo=1002', 'ToAccountNo=1002'):
            self.assert_rejected(f"UPDATE TransferDetails SET {changes} WHERE TransactionID={transaction}",
                                 'cannot be reassigned')
        self.assertEqual(self.execute("SELECT COUNT(*) FROM transfer_integrity_violations"), '0')

    def test_transfer_audit_detects_administrative_import_omissions(self):
        for status in ('PENDING','SUCCESS','FAILED'):
            transaction = self.execute("INSERT INTO BankTransaction "
                "(AccountNo,TransactionType,Amount,Status,RequestID) "
                f"VALUES (NULL,'TRANSFER',1,'{status}','audit-{status}'); SELECT LAST_INSERT_ID();")
            self.assertEqual(self.execute("SELECT Status FROM transfer_integrity_violations "
                                          f"WHERE TransactionID={transaction}"), status)
            self.execute("INSERT INTO TransferDetails (TransactionID,FromAccountNo,ToAccountNo) "
                         f"VALUES ({transaction},1001,2001)")
            self.assertEqual(self.execute("SELECT COUNT(*) FROM transfer_integrity_violations "
                                          f"WHERE TransactionID={transaction}"), '0')

    def test_missing_accounts(self):
        self.assert_rejected("CALL Deposit(9999,1,NULL,'missing',@id)", "does not exist")
        self.assert_rejected("CALL Withdraw(9999,1,NULL,'missing',@id)", "does not exist")
        for source, target in ((999,1001), (1001,9999), (9999,1001)):
            self.assert_rejected(f"CALL Transfer({source},{target},1,NULL,'missing',@id)",
                                 "does not exist")

    def test_inactive_and_fixed_deposit_accounts(self):
        for status in ("FROZEN", "CLOSED"):
            self.execute(f"UPDATE Account SET Status='{status}' WHERE AccountNo=1001")
            self.assert_rejected("CALL Deposit(1001,1,NULL,'inactive',@id)", "active")
            self.assert_rejected("CALL Withdraw(1001,1,NULL,'inactive',@id)", "active")
            self.assert_rejected("CALL Transfer(1002,1001,1,NULL,'inactive',@id)", "active")
        for call in ("Deposit(4001,1,NULL,'fd',@id)", "Withdraw(4001,1,NULL,'fd',@id)",
                     "Transfer(4001,1002,1,NULL,'fd',@id)",
                     "Transfer(1002,4001,1,NULL,'fd',@id)"):
            self.assert_rejected("CALL " + call, "fixed deposit")

    def test_minimum_balance_and_insufficient_funds(self):
        for account in (1001, 1002):
            for amount in (901, 1001):
                self.assert_rejected(f"CALL Withdraw({account},{amount},NULL,'low',@id)",
                                     "Insufficient funds")
                self.assert_rejected(f"CALL Transfer({account},2001,{amount},NULL,'low',@id)",
                                     "Insufficient funds")
        self.execute("CALL Withdraw(1001,900,NULL,'boundary',@id)")
        self.assertEqual(self.balance(1001), Decimal("100"))

    def test_missing_source_subtype(self):
        self.execute("TRUNCATE TABLE SavingsAccount")
        self.assert_rejected("CALL Withdraw(1001,1,NULL,'missing',@id)", "subtype record is missing")
        self.assert_rejected("CALL Transfer(1001,2001,1,NULL,'missing',@id)", "subtype record is missing")

    def test_overflow(self):
        self.execute("UPDATE Account SET Balance=9999999999999.99 WHERE AccountNo=2001")
        self.assert_rejected("CALL Deposit(2001,0.01,NULL,'overflow',@id)", "balance limit")
        self.assert_rejected("CALL Transfer(1001,2001,0.01,NULL,'overflow',@id)", "balance limit")
        self.execute("UPDATE Account SET Balance=9999999999999.99 WHERE AccountNo=3001")
        self.assert_rejected("CALL Transfer(1001,3001,0.01,NULL,'overflow-bank',@id)", "balance limit")

    def test_cross_bank_transfers_both_directions_and_reporting(self):
        self.execute("CALL Transfer(1001,3001,200,'ONLINE','bank-out',@id);")
        self.execute("CALL Transfer(3001,1002,50,'ONLINE','bank-in',@id);")
        self.assertEqual(self.balance(1001), Decimal('800'))
        self.assertEqual(self.balance(3001), Decimal('1150'))
        self.assertEqual(self.balance(1002), Decimal('1050'))
        self.assertEqual(self.execute("SELECT SourceBankID,DestinationBankID,TransferScope "
                                      "FROM transaction_history ORDER BY TransactionID"),
                         '1\t2\tINTER_BANK\n2\t1\tINTER_BANK')
        self.assert_rejected("CALL Transfer(1001,3001,200,'ONLINE','bank-out',@id)", 'Duplicate entry')

    def test_cross_bank_minimum_balance_and_inactive_destination(self):
        self.assert_rejected("CALL Transfer(1001,3001,901,NULL,'bank-min',@id)", 'minimum balance')
        self.execute("UPDATE Account SET Status='FROZEN' WHERE AccountNo=3001")
        self.assert_rejected("CALL Transfer(1001,3001,100,NULL,'bank-frozen',@id)", 'must be active')

    def test_duplicate_request_across_operations(self):
        self.execute("CALL Deposit(1001,10,NULL,'duplicate',@id)")
        for call in ("Deposit(1001,10,NULL,'duplicate',@id)",
                     "Withdraw(1001,10,NULL,'duplicate',@id)",
                     "Transfer(1001,2001,10,NULL,'duplicate',@id)"):
            self.assert_rejected("CALL " + call, "Duplicate entry")

    def test_failure_after_source_debit_rolls_back_everything(self):
        self.execute("""
            DELIMITER $$
            CREATE TRIGGER test_fail_credit BEFORE UPDATE ON Account FOR EACH ROW
            BEGIN
                IF NEW.AccountNo=3001 THEN
                    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Injected credit failure';
                END IF;
            END$$
            DELIMITER ;
        """)
        try:
            self.assert_rejected("CALL Transfer(1001,3001,100,NULL,'failure',@id)",
                                 "Injected credit failure")
        finally:
            self.execute("DROP TRIGGER test_fail_credit")

    def test_existing_transaction_is_not_committed_or_rolled_back(self):
        result = self.run_sql("""
            START TRANSACTION;
            UPDATE Account SET Balance=1234 WHERE AccountNo=1001;
            CALL Deposit(1001,10,NULL,'nested',@id);
            SELECT Balance FROM Account WHERE AccountNo=1001;
            ROLLBACK;
        """, force=True)
        self.assertIn("Transaction characteristics can't be changed", result.stderr)
        self.assertEqual(result.stdout.strip(), "1234.00")
        self.assertEqual(self.balance(1001), Decimal("1000"))

    def test_concurrent_deposits_have_no_lost_updates(self):
        with ThreadPoolExecutor(max_workers=8) as pool:
            list(pool.map(lambda i: self.execute(f"CALL Deposit(1001,1,NULL,'concurrent-{i}',@id)"),
                          range(24)))
        self.assertEqual(self.balance(1001), Decimal("1024"))
        self.assertEqual(self.execute("SELECT COUNT(*) FROM BankTransaction"), "24")

    def test_concurrent_withdrawals_cannot_overspend(self):
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(lambda i: self.run_sql(
                f"CALL Withdraw(1001,600,NULL,'race-{i}',@id)"), range(2)))
        self.assertEqual(sum(r.returncode == 0 for r in results), 1)
        self.assertEqual(self.balance(1001), Decimal("400"))
        self.assertEqual(self.execute("SELECT COUNT(*) FROM BankTransaction"), "1")

    def test_concurrent_opposite_transfers_preserve_total(self):
        def transfer(i):
            source, target = (1001, 2001) if i % 2 else (2001, 1001)
            self.execute(f"CALL Transfer({source},{target},1,NULL,'opposite-{i}',@id)")
        with ThreadPoolExecutor(max_workers=8) as pool:
            list(pool.map(transfer, range(24)))
        self.assertEqual(self.balance(1001), Decimal("1000"))
        self.assertEqual(self.balance(2001), Decimal("1000"))
        self.assertEqual(self.execute("SELECT COUNT(*) FROM TransferDetails"), "24")

    def test_concurrent_duplicate_request_applies_once(self):
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(lambda _: self.run_sql(
                "CALL Deposit(1001,10,NULL,'same-request',@id)"), range(2)))
        self.assertEqual(sum(r.returncode == 0 for r in results), 1)
        self.assertEqual(self.balance(1001), Decimal("1010"))
        self.assertEqual(self.execute("SELECT COUNT(*) FROM BankTransaction"), "1")

    def test_concurrent_opposite_cross_bank_transfers_preserve_balances(self):
        def transfer(i):
            source, target = (1001, 3001) if i % 2 else (3001, 1001)
            self.execute(f"CALL Transfer({source},{target},1,NULL,'bank-opposite-{i}',@id)")
        with ThreadPoolExecutor(max_workers=8) as pool:
            list(pool.map(transfer, range(24)))
        self.assertEqual(self.balance(1001), Decimal('1000'))
        self.assertEqual(self.balance(3001), Decimal('1000'))
        self.assertEqual(self.execute("SELECT COUNT(*) FROM transaction_history "
                                      "WHERE TransferScope='INTER_BANK' AND Status='SUCCESS'"), '24')


if __name__ == "__main__":
    unittest.main()
